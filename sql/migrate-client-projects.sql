-- Client projects, discounts, and comments (2026-11-16): Phase 1
-- of the dashboard redesign. Run once in the D1 Console
-- (gray-solutions-db). Safe to re-run: the CREATEs are IF NOT
-- EXISTS, the discount seeds are INSERT OR IGNORE, and the copy
-- skips (client, type) pairs already present in client_project.
--
-- What this adds:
--   discounts — one row per client: their total earned discount
--     percent, plus how many leads they've generated. Keyed by
--     client_id, NOT by token: tokens stay in referral_tokens,
--     and the Workers look a client's tokens up by client_id when
--     they need them.
--   client_project — the per-client project history: installs,
--     features, and tier upgrades, each with its own tier, price,
--     status, and remaining balance. Replaces client_pricing.
--   project_comments — the comment thread on a project, shared by
--     the admin and client dashboards.
--   referral_leads — one attribution per lead, so the +10/+5
--     discount ladder counts each lead exactly once.
--
-- The discount seeds below encode the current reality: Ian's
-- install is complete and paid (a $0 service swap), so he starts
-- at the 15% floor every completed-and-paid project earns;
-- everyone else starts at 0 with no leads. The 15% is a floor,
-- never a reduction: a larger earned discount is never lowered
-- to it.
--
-- The copy below moves every client_pricing row into
-- client_project: tier and quoted price verbatim; billed rows
-- become complete with a $0 balance and their completion reward
-- already applied; quoted-but-unbilled rows become quoted with
-- the full price still owed; unquoted rows become new.
--
-- client_pricing is NOT dropped here. It stays until the Phase 2
-- code is verified live against client_project; dropping it is a
-- separate step.

-- Discounts: one row per client holding their total earned
-- discount percent and how many leads they've generated. The
-- percent is a total: 15 when a project completes and is paid (a
-- floor), +10 on the first generated lead, +5 per lead after,
-- capped at 50. Quote-time caps apply per project type (install
-- 25%, feature/upgrade 50%) — the cap lives in the quoting code,
-- not here.
CREATE TABLE IF NOT EXISTS discounts (
  id INTEGER PRIMARY KEY,
  client_id INTEGER NOT NULL UNIQUE REFERENCES clients(id),
  -- Total earned percent off, 0-50.
  discount_pct INTEGER NOT NULL DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 50),
  -- Leads this client has generated (rows in referral_leads).
  leads_count INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Client projects: the per-client project history. The id is a
-- 7-character lowercase hex "short SHA", generated by the Workers
-- (and by the migration copy for migrated rows) — short enough to
-- quote in email subjects and reply-to addresses.
CREATE TABLE IF NOT EXISTS client_project (
  -- Short SHA id, e.g. 'a3f9c21'. TEXT PRIMARY KEY: ids are
  -- generated, never sequential.
  id TEXT PRIMARY KEY,
  client_id INTEGER NOT NULL REFERENCES clients(id),
  -- 'install' = the first project, a new site build; 'feature' =
  -- new capability on an existing site; 'upgrade' = moving the
  -- site to a higher tier.
  type TEXT NOT NULL CHECK (type IN ('install', 'feature', 'upgrade')),
  -- Display name, e.g. 'Website install'. Admin-editable.
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  -- The tier this project prices from. NULL until a tier is
  -- picked; the tier is only the default cost basis — price_cents
  -- is the authoritative quote and may differ.
  tier_id INTEGER REFERENCES pricing_tiers(id),
  -- The quoted price after discount, in cents. NULL = unquoted.
  price_cents INTEGER,
  -- In order: new, designing, quoted, in_progress, pending_payment
  -- (a downpayment is required before the site ships),
  -- pending_approval, complete.
  status TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'designing', 'quoted', 'in_progress', 'pending_payment', 'pending_approval', 'complete')),
  -- What the client still owes, in cents. NULL = unset. Updated by
  -- hand until a payment system lands.
  remaining_balance_cents INTEGER,
  -- The discounts row whose percent was applied to this project's
  -- quote (a snapshot link, not a live join).
  discount_id INTEGER REFERENCES discounts(id),
  -- The client request this project came from, if any. NULL for
  -- projects created directly by the admin or copied here.
  request_id INTEGER REFERENCES client_requests(id),
  -- 1 once the completion reward (the 15% floor + referral token)
  -- has been applied for this project — it must fire exactly once.
  completion_reward_applied INTEGER NOT NULL DEFAULT 0 CHECK (completion_reward_applied IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_client_project_client ON client_project(client_id);

-- Project comments: the conversation thread on a project. Comments
-- send emails and drive notification badges on both dashboards.
CREATE TABLE IF NOT EXISTS project_comments (
  id INTEGER PRIMARY KEY,
  project_id TEXT NOT NULL REFERENCES client_project(id) ON DELETE CASCADE,
  -- The commenter's email address (chris@ or the client's).
  comment_owner TEXT NOT NULL,
  comment_text TEXT NOT NULL,
  -- R2 object key for an attached image, if any. NULL = no image.
  image_key TEXT,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  -- When the counterparty read it. NULL = unread; the owner never
  -- needs to read their own comment.
  read_at TEXT
);

CREATE INDEX IF NOT EXISTS idx_project_comments_project ON project_comments(project_id);

-- Referral leads: one row per lead a client's sharing brought in.
-- lead_client_id is UNIQUE: one attribution per lead, so the
-- +10/+5 discount ladder counts each lead exactly once no matter
-- how many times a token is opened or a contact form is submitted.
CREATE TABLE IF NOT EXISTS referral_leads (
  id INTEGER PRIMARY KEY,
  referrer_client_id INTEGER NOT NULL REFERENCES clients(id),
  lead_client_id INTEGER NOT NULL UNIQUE REFERENCES clients(id),
  -- The token the lead arrived with.
  token TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- Seeds: one discounts row per existing client. 15 for an
-- established client with a billed install row (today: Ian, the
-- completed-and-paid service swap); 0 for everyone else. The
-- UNIQUE on client_id makes this safe to re-run.
INSERT OR IGNORE INTO discounts (client_id, discount_pct, leads_count)
SELECT
  c.id,
  CASE WHEN c.is_client = 1 AND EXISTS (
    SELECT 1 FROM client_pricing cp
    WHERE cp.client_id = c.id AND cp.project_type = 'install' AND cp.billed = 1
  ) THEN 15 ELSE 0 END,
  0
FROM clients c;

-- Copy: every client_pricing row becomes one client_project row.
-- Pairs already present are skipped, so re-running adds nothing.
INSERT INTO client_project (id, client_id, type, name, description, tier_id, price_cents, status, remaining_balance_cents, discount_id, request_id, completion_reward_applied)
SELECT
  substr(lower(hex(randomblob(4))), 1, 7),
  cp.client_id,
  cp.project_type,
  CASE WHEN cp.project_type = 'install' THEN 'Website install' ELSE 'Feature work' END,
  '',
  cp.tier_id,
  cp.quoted_price_cents,
  CASE WHEN cp.billed = 1 THEN 'complete'
       WHEN cp.quoted_price_cents IS NOT NULL THEN 'quoted'
       ELSE 'new' END,
  CASE WHEN cp.billed = 1 THEN 0 ELSE cp.quoted_price_cents END,
  d.id,
  NULL,
  CASE WHEN cp.billed = 1 THEN 1 ELSE 0 END
FROM client_pricing cp
LEFT JOIN discounts d ON d.client_id = cp.client_id
WHERE NOT EXISTS (
  SELECT 1 FROM client_project p
  WHERE p.client_id = cp.client_id AND p.type = cp.project_type
);
